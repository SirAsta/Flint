#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Number(f64),
    Str(String),
    Ident(String),
    Let,
    If,
    Else,
    Elif,
    While,
    For,
    In,
    Fn,
    Return,
    Import,
    Class,
    This,
    Break,
    Continue,
    True,
    False,
    Null,
    And,
    Or,
    Not,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Semicolon,
    Colon,
    Dot,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    EqEq,
    BangEq,
    Less,
    LessEq,
    Greater,
    GreaterEq,
    Assign,
    Eof,
}

#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub line: usize,
}
